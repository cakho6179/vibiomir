import pandas as pd, sys, re, numpy as np
sys.stdout.reconfigure(encoding="utf-8")
pd.set_option("display.width",250); pd.set_option("display.max_rows",300)
c=pd.read_pickle("corpus.pkl")
u=c.url.astype(str)
c["host"]=u.str.extract(r"^[a-z]+://([^/]+)")[0].str.lower().str.replace(r"^www\.","",regex=True)
ZH=set(["120ask.com","cnkang.com","familydoctor.com.cn","ask.39.net","youlai.cn","zhongyibaodian.net","zysjonline.com","msdmanuals.cn","a-hospital.com","wujue.com","zydcd.com","article.iiyi.com","jb39.com","jbk.39.net","test.pmphai.com","baidu.com","familydoctor.cn","qihuangzhishu.com","health.people.com.cn","qy.familydoctor.com.cn","ask.familydoctor.com.cn","bingli.iiyi.com","baidianfeng.familydoctor.com.cn"]) | set(h for h in c.host.unique() if h.endswith(".39.net"))
c["lang"]=np.where(c.host=="pubmed.ncbi.nlm.nih.gov","en",np.where(c.host.isin(ZH),"zh","vi"))
print("LANG:",c.lang.value_counts().to_dict())
o=c.sort_values("id")
# host sequence run-length in id order
seq=o.host.values
chg=np.concatenate([[0],np.where(seq[1:]!=seq[:-1])[0]+1])
print("num host-runs in id order:",len(chg))
blocks=[(seq[a],o.id.values[a],o.id.values[b]) for a,b in zip(chg,np.append(chg[1:]-1,len(seq)-1))]
print("first 15 host-runs (host, id_start, id_end):")
for x in blocks[:15]: print("   ",x)
print("...")
print("runs where the same host appears >1 time:",pd.Series([b[0] for b in blocks]).value_counts().head(20).to_dict())
print("total runs:",len(blocks),"unique hosts in runs:",len(set(b[0] for b in blocks)))
o.to_pickle("corpus_ord.pkl")
# PMID analysis
pub=o[o.host=="pubmed.ncbi.nlm.nih.gov"].copy()
pmid=pub.url.str.extract(r"/(\d+)/")[0].astype(np.int64)
print()
print("=== PUBMED ===")
print("n",len(pmid),"min",pmid.min(),"max",pmid.max())
print("pmid quantiles",np.percentile(pmid,[1,5,25,50,75,95,99]).round(0).tolist())
print("dup pmids",pmid.duplicated().sum())
print("corr(id, pmid) = %.4f"%np.corrcoef(pub.id.values,pmid.values)[0,1])
print("spearman-ish (rank corr) = %.4f"%pd.Series(pub.id.values).corr(pd.Series(pmid.values),method="spearman"))
print("id contiguous within pubmed?", (np.diff(np.sort(pub.id.values))>1).sum(),"gaps in",len(pub))
